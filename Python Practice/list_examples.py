# Creating a List
numbers = [1, 2, 3, 4, 5]
print(numbers)

# List with Different Data Types
data = [10, "Python", 3.14, True]

print(data)

# Accessing List Elements
fruits = ["apple", "banana", "mango"]

print(fruits[0])
print(fruits[1])

# List Slicing
numbers = [1, 2, 3, 4, 5]

print(numbers[1:4])
print(numbers[:3])
print(numbers[2:])

#Changing List Elements
fruits = ["apple", "banana", "mango"]

fruits[1] = "orange"

print(fruits)

# Removing Elements
fruits = ["apple", "banana", "mango"]
fruits.remove("banana")
print(fruits)