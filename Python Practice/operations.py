# Arithmetic Operations

a = 10
b = 3

print("A Value:", a)

print("B Value:", b)

print("A B Addition Value:", a + b)

print("A B Subtraction Value:", a - b)

print("A B Multiplication Value:", a * b)

print("A B Division Value:", a / b)

print("A B Floor Division Value:", a // b)

print("A B Modulus Value:", a % b)

print("A B Power Value:", a ** b)

# Comparison Operations

x = 5
y = 10

print("X Value:", x)

print("Y Value:", y)

print("X and Y are Equal:", x == y)

print("X and Y are Not Equal:", x != y)

print("X is Greater Than Y:", x > y)

print("X is Less Than Y:", x < y)

# Assignment Operations
x = 10

x += 5
print(x)

x *= 2
print(x)